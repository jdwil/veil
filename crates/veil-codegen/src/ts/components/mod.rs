/// Generate the `<style>` section by parsing CSS into CssExpr nodes.
///
/// Handles common patterns:
/// - Simple rules: `.card { padding: 1rem; }`
/// - Custom properties: `--color: #fff;`
/// - Media queries: `@media (...) { ... }`
/// - @keyframes
///
/// Complex or unrecognized patterns pass through as `CssExpr::Raw`.
fn generate_style_section(comp: &Construct) -> String {
    let style_content = get_raw_block(comp, "style");

    let content = if style_content.is_empty() {
        // Fallback: check fns named "style" (old pattern)
        get_fn_string_body(comp, "style")
    } else {
        style_content
    };

    if content.is_empty() {
        return "  /* TODO: Add component styles */\n".to_string();
    }

    let nodes = parse_css_to_exprs(&content);
    if nodes.is_empty() {
        return format!("  {}\n", content.trim());
    }

    let emitted = emit_css_nodes(&nodes, 1);
    format!("{}\n", emitted)
}

/// Parse CSS text into CssExpr nodes.
///
/// Best-effort mini-parser. Handles:
/// - Standard rules: `selector { declarations }`
/// - @media queries
/// - @keyframes
/// - @import
/// - Custom properties at :root level
///
/// Unrecognized patterns become `CssExpr::Raw`.
pub fn parse_css_to_exprs(input: &str) -> Vec<CssExpr> {
    let input = input.trim();
    if input.is_empty() {
        return vec![];
    }

    let mut nodes = Vec::new();
    let mut pos = 0;
    let chars: Vec<char> = input.chars().collect();

    while pos < chars.len() {
        // Skip whitespace
        while pos < chars.len() && chars[pos].is_whitespace() {
            pos += 1;
        }
        if pos >= chars.len() {
            break;
        }

        // @import
        if starts_with_at(&chars, pos, "@import") {
            if let Some(end) = find_char(&chars, pos, ';') {
                let line: String = chars[pos..end + 1].iter().collect();
                let path = line
                    .trim_start_matches("@import")
                    .trim()
                    .trim_matches(|c| c == '"' || c == '\'' || c == ';')
                    .trim()
                    .to_string();
                nodes.push(CssExpr::Import(path));
                pos = end + 1;
                continue;
            }
        }

        // @media
        if starts_with_at(&chars, pos, "@media") {
            if let Some((node, end)) = parse_media_query(&chars, pos) {
                nodes.push(node);
                pos = end;
                continue;
            }
        }

        // @keyframes
        if starts_with_at(&chars, pos, "@keyframes") {
            if let Some((node, end)) = parse_keyframes(&chars, pos) {
                nodes.push(node);
                pos = end;
                continue;
            }
        }

        // Regular rule: selector { declarations }
        if let Some((node, end)) = parse_css_rule(&chars, pos) {
            nodes.push(node);
            pos = end;
            continue;
        }

        // Fallback: collect line as raw
        let line_start = pos;
        while pos < chars.len() && chars[pos] != '\n' {
            pos += 1;
        }
        let line: String = chars[line_start..pos].iter().collect();
        let line = line.trim();
        if !line.is_empty() {
            nodes.push(CssExpr::Raw(line.to_string()));
        }
        if pos < chars.len() {
            pos += 1;
        }
    }

    nodes
}

fn parse_css_rule(chars: &[char], pos: usize) -> Option<(CssExpr, usize)> {
    // Find the opening brace
    let brace_pos = find_char(chars, pos, '{')?;

    // Selector is everything before the brace
    let selector: String = chars[pos..brace_pos].iter().collect();
    let selector = selector.trim().to_string();
    if selector.is_empty() {
        return None;
    }

    // Find matching closing brace
    let close_pos = find_matching_css_brace(chars, brace_pos)?;
    let body: String = chars[brace_pos + 1..close_pos].iter().collect();

    // Check if body contains nested rules (has { in it)
    if body.contains('{') {
        // Nested rules — parse as Nest
        let children = parse_css_to_exprs(&body);
        return Some((
            CssExpr::Nest { parent: selector, children },
            close_pos + 1,
        ));
    }

    // Parse declarations
    let declarations = parse_declarations(&body);

    Some((
        CssExpr::Rule { selector, declarations },
        close_pos + 1,
    ))
}

fn parse_media_query(chars: &[char], pos: usize) -> Option<(CssExpr, usize)> {
    let brace_pos = find_char(chars, pos, '{')?;
    let header: String = chars[pos..brace_pos].iter().collect();
    let condition = header
        .trim_start_matches("@media")
        .trim()
        .to_string();

    let close_pos = find_matching_css_brace(chars, brace_pos)?;
    let body: String = chars[brace_pos + 1..close_pos].iter().collect();

    let rules = parse_css_to_exprs(&body);

    Some((
        CssExpr::MediaQuery { condition, rules },
        close_pos + 1,
    ))
}

fn parse_keyframes(chars: &[char], pos: usize) -> Option<(CssExpr, usize)> {
    let brace_pos = find_char(chars, pos, '{')?;
    let header: String = chars[pos..brace_pos].iter().collect();
    let name = header
        .trim_start_matches("@keyframes")
        .trim()
        .to_string();

    let close_pos = find_matching_css_brace(chars, brace_pos)?;
    let body: String = chars[brace_pos + 1..close_pos].iter().collect();

    // Parse keyframe steps (e.g. "from { ... }" "to { ... }" "50% { ... }")
    let step_rules = parse_css_to_exprs(&body);
    let steps: Vec<(String, Vec<CssDeclaration>)> = step_rules
        .into_iter()
        .filter_map(|rule| {
            if let CssExpr::Rule { selector, declarations } = rule {
                Some((selector, declarations))
            } else {
                None
            }
        })
        .collect();

    Some((
        CssExpr::Keyframes { name, steps },
        close_pos + 1,
    ))
}

fn parse_declarations(body: &str) -> Vec<CssDeclaration> {
    let mut declarations = Vec::new();
    for part in body.split(';') {
        let part = part.trim();
        if part.is_empty() {
            continue;
        }
        if let Some((prop, val)) = part.split_once(':') {
            declarations.push(CssDeclaration {
                property: prop.trim().to_string(),
                value: val.trim().to_string(),
            });
        }
    }
    declarations
}

