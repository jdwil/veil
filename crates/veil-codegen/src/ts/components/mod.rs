/// Get a named raw_block from a construct.
fn get_raw_block(comp: &Construct, name: &str) -> String {
    comp.raw_blocks
        .iter()
        .find(|(n, _)| n == name)
        .map(|(_, content)| content.clone())
        .unwrap_or_default()
}

/// Fallback: get string body from a fn named `name` (old pattern).
fn get_fn_string_body(comp: &Construct, name: &str) -> String {
    comp.fns
        .iter()
        .find(|f| f.name == name)
        .and_then(|f| {
            f.body.first().and_then(|expr| match expr {
                Expr::StringLit(s) => Some(s.clone()),
                Expr::Return(inner) => {
                    if let Expr::StringLit(s) = inner.as_ref() {
                        Some(s.clone())
                    } else {
                        None
                    }
                }
                _ => None,
            })
        })
        .unwrap_or_default()
}

/// Detect PascalCase component references in template text for auto-imports.
fn detect_component_imports(template: &str, self_name: &str) -> Vec<String> {
    let mut imports = Vec::new();
    let chars: Vec<char> = template.chars().collect();
    let mut i = 0;
    while i < chars.len() {
        if chars[i] == '<' && i + 1 < chars.len() && chars[i + 1].is_uppercase() {
            i += 1;
            let mut comp_name = String::new();
            while i < chars.len() && (chars[i].is_alphanumeric() || chars[i] == '_') {
                comp_name.push(chars[i]);
                i += 1;
            }
            if !comp_name.is_empty() && comp_name != self_name && !imports.contains(&comp_name) {
                imports.push(comp_name);
            }
        } else {
            i += 1;
        }
    }
    imports
}

/// Build props destructuring bindings string from fields and reactivity policy.
fn build_props_bindings(fields: &[veil_ir::ast::Field], pol: &ReactivityPolicy) -> String {
    fields
        .iter()
        .map(|field| {
            let is_bind = field
                .annotations
                .iter()
                .any(|a| a.name == "bind" || a.name == "bindable");

            if let Some(expr) = &field.default_expr {
                if is_bind && !pol.bindable.is_empty() {
                    let def = expr_to_ts(expr, 1);
                    let bind_expr = if def == "undefined" || def.is_empty() {
                        pol.bindable.clone()
                    } else {
                        ReactivityPolicy::fill(
                            &pol.bindable_default,
                            &[("default", def.as_str())],
                        )
                    };
                    format!("{} = {}", field.name, bind_expr)
                } else {
                    format!("{} = {}", field.name, expr_to_ts(expr, 1))
                }
            } else if is_bind && !pol.bindable.is_empty() {
                format!("{} = {}", field.name, pol.bindable)
            } else {
                field.name.clone()
            }
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// Get a default value for a TypeScript type.
fn default_value_for_ts(ty: &str) -> &str {
    match ty {
        "boolean" => "false",
        "number" => "0",
        "string" => "''",
        _ if ty.ends_with("[]") => "[]",
        _ if ty.ends_with("| null") => "null",
        _ => "undefined as any",
    }
}

/// Check if an effect body contains async operations.
fn effect_body_needs_await(body: &[Expr]) -> bool {
    body.iter().any(|expr| expr_needs_await(expr))
}

fn expr_needs_await(expr: &Expr) -> bool {
    match expr {
        Expr::Await(_) | Expr::Try(_) => true,
        Expr::Call(_) => false, // Can't know without context
        Expr::Assign(_, rhs, _) | Expr::MutAssign(_, rhs, _) => expr_needs_await(rhs),
        Expr::IfExpr(data) => {
            data.then_body.iter().any(|e| expr_needs_await(e))
                || data.else_body.as_ref().map_or(false, |b| b.iter().any(|e| expr_needs_await(e)))
        }
        Expr::Return(inner) => expr_needs_await(inner),
        _ => false,
    }
}

/// Emit an expression as async TypeScript (wraps await where needed).
fn expr_to_ts_async(expr: &Expr, indent: usize) -> String {
    // Delegate to the existing async emission path
    crate::typescript::expr_to_ts_async(expr, indent)
}

/// Convert component HtmlAttrs to prop tuples for HtmlExpr::Component.
fn attrs_to_component_props(attrs: &[HtmlAttr]) -> Vec<(String, String)> {
    attrs
        .iter()
        .filter_map(|attr| match &attr.value {
            HtmlAttrValue::Static(val) => Some((attr.name.clone(), format!("\"{}\"", val))),
            HtmlAttrValue::Dynamic(expr) => Some((attr.name.clone(), expr.clone())),
            HtmlAttrValue::Bind(prop) => Some((format!("bind:{}", prop), prop.clone())),
            HtmlAttrValue::Event(event, handler) => {
                Some((format!("on:{}", event), handler.clone()))
            }
            HtmlAttrValue::Spread(expr) => Some(("...".to_string(), expr.clone())),
            HtmlAttrValue::Boolean => Some((attr.name.clone(), "true".to_string())),
        })
        .collect()
}

/// Remove common leading indentation from a multi-line string block.
fn dedent_block(s: &str) -> String {
    let lines: Vec<&str> = s.lines().collect();
    if lines.is_empty() {
        return String::new();
    }
    let min_indent = lines
        .iter()
        .filter(|l| !l.trim().is_empty())
        .map(|l| l.len() - l.trim_start().len())
        .min()
        .unwrap_or(0);
    lines
        .iter()
        .map(|l| {
            if l.len() > min_indent {
                &l[min_indent..]
            } else {
                l.trim()
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

// ─── Parsing Utilities ───────────────────────────────────────────────────────

/// Check if chars at `pos` starts with a given string.
fn starts_with_at(chars: &[char], pos: usize, s: &str) -> bool {
    let s_chars: Vec<char> = s.chars().collect();
    if pos + s_chars.len() > chars.len() {
        return false;
    }
    for (i, c) in s_chars.iter().enumerate() {
        if chars[pos + i] != *c {
            return false;
        }
    }
    true
}

/// Find a character starting from `pos`.
fn find_char(chars: &[char], start: usize, ch: char) -> Option<usize> {
    for i in start..chars.len() {
        if chars[i] == ch {
            return Some(i);
        }
    }
    None
}

/// Find a substring starting from `pos`.
fn find_str(chars: &[char], start: usize, s: &str) -> Option<usize> {
    let s_chars: Vec<char> = s.chars().collect();
    if s_chars.is_empty() {
        return Some(start);
    }
    for i in start..chars.len() {
        if starts_with_at(chars, i, s) {
            return Some(i);
        }
    }
    None
}

/// Find matching closing brace `}` for an opening brace at `pos`, respecting nesting.
fn find_matching_brace(chars: &[char], pos: usize) -> Option<usize> {
    if pos >= chars.len() || chars[pos] != '{' {
        return None;
    }
    let mut depth = 0;
    for i in pos..chars.len() {
        match chars[i] {
            '{' => depth += 1,
            '}' => {
                depth -= 1;
                if depth == 0 {
                    return Some(i);
                }
            }
            _ => {}
        }
    }
    None
}

/// Find matching closing brace for CSS (handles nested rules).
fn find_matching_css_brace(chars: &[char], pos: usize) -> Option<usize> {
    find_matching_brace(chars, pos)
}

/// Find a block end tag (e.g. `{/each}`, `{/if}`).
fn find_block_end(chars: &[char], start: usize, end_tag: &str) -> Option<usize> {
    // We need to respect nesting of the same block type
    let open_prefix = if end_tag.starts_with("{/") {
        let keyword = end_tag.trim_start_matches("{/").trim_end_matches('}');
        format!("{{#{}", keyword)
    } else {
        return find_str(chars, start, end_tag);
    };

    let mut depth = 1;
    let mut pos = start;
    while pos < chars.len() {
        if starts_with_at(chars, pos, &open_prefix) {
            depth += 1;
            pos += open_prefix.len();
        } else if starts_with_at(chars, pos, end_tag) {
            depth -= 1;
            if depth == 0 {
                return Some(pos);
            }
            pos += end_tag.len();
        } else {
            pos += 1;
        }
    }
    None
}

/// Split an if block body into then/else parts, finding `{:else}` and `{/if}`.
fn split_if_else(chars: &[char], start: usize) -> Option<(String, String, usize)> {
    let mut depth = 1;
    let mut pos = start;
    let mut else_pos = None;

    while pos < chars.len() {
        if starts_with_at(chars, pos, "{#if") {
            depth += 1;
            pos += 4;
        } else if starts_with_at(chars, pos, "{/if}") {
            depth -= 1;
            if depth == 0 {
                let end_pos = pos + 5;
                let then_end = else_pos.unwrap_or(pos);
                let then_content: String = chars[start..then_end].iter().collect();
                let else_content = if let Some(ep) = else_pos {
                    let else_start = ep + 7; // after "{:else}"
                    chars[else_start..pos].iter().collect::<String>()
                } else {
                    String::new()
                };
                return Some((then_content, else_content, end_pos));
            }
            pos += 5;
        } else if starts_with_at(chars, pos, "{:else}") && depth == 1 {
            else_pos = Some(pos);
            pos += 7;
        } else if starts_with_at(chars, pos, "{:else if ") && depth == 1 {
            // Treat {:else if ...} as the else branch start
            else_pos = Some(pos);
            pos += 1;
        } else {
            pos += 1;
        }
    }

    None
}

