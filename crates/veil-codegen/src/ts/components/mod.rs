//! Svelte 5 component generation using structured IRs.
//!
//! Ports `gen_svelte_file` from `typescript.rs` to use the new TsExpr/HtmlExpr/CssExpr
//! intermediate representations. The three sections of a `.svelte` file are:
//!
//! 1. `<script lang="ts">` → TsExpr nodes → `emit_ts()`
//! 2. Template → HtmlExpr nodes → `emit_html()`
//! 3. `<style>` → CssExpr nodes → `emit_css()`
//!
//! Each section has its own mini-parser (for template/style raw blocks) or
//! structural lowering (for script blocks using VEIL IR fields).

