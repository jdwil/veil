// ─── Public API ──────────────────────────────────────────────────────────────

/// Generated Svelte component file (path + content).
pub struct SvelteFile {
    pub path: String,
    pub content: String,
}

/// Generate a complete `.svelte` file from a Component construct using the
/// structured IR pipeline (TsExpr → emit_ts, HtmlExpr → emit_html, CssExpr → emit_css).
///
/// Default output path: `src/lib/components/{name}.svelte`.
/// Use [`gen_svelte_component_at`] for SvelteKit routing paths.
pub fn gen_svelte_component(comp: &Construct, registry: &LayerRegistry) -> SvelteFile {
    let path = format!("src/lib/components/{}.svelte", comp.name);
    gen_svelte_component_at(comp, registry, &path)
}

/// Generate a `.svelte` file at a specific output path.
///
/// Used by the SvelteKit integration to place pages at
/// `src/routes/{route}/+page.svelte` and layouts at `+layout.svelte`.
pub fn gen_svelte_component_at(comp: &Construct, registry: &LayerRegistry, path: &str) -> SvelteFile {
    let script = generate_script_section(comp, registry);
    let template = generate_template_section(comp);
    let style = generate_style_section(comp);

    let content = format!(
        "<script lang=\"ts\">\n{}</script>\n\n{}\n\n<style>\n{}\n</style>\n",
        script, template, style,
    );

    SvelteFile { path: path.to_string(), content }
}

/// Generate a Svelte 5 rune-based store file (`.svelte.ts`).
///
/// Stores use `$state()` runes exported from a `.svelte.ts` module rather than
/// the old `writable()`/`readable()` API. Output path: `src/lib/stores/{name}.svelte.ts`.
pub fn gen_svelte_store(comp: &Construct, _registry: &LayerRegistry) -> SvelteFile {
    gen_svelte_store_at(comp, _registry, &format!("src/lib/stores/{}.svelte.ts", to_snake(&comp.name)))
}

/// Generate a Svelte 5 rune-based store file at a specific output path.
pub fn gen_svelte_store_at(comp: &Construct, _registry: &LayerRegistry, path: &str) -> SvelteFile {
    let mut out = String::new();
    out.push_str(&format!("// {} — Svelte 5 rune-based store (generated by VEIL)\n\n", comp.name));

    // State fields → exported $state runes
    let state_block = comp.blocks.iter().find(|b| b.keyword == "state");
    if let Some(state) = state_block {
        for field in &state.fields {
            let ty = field_type_ts(field);
            let default = if let Some(expr) = &field.default_expr {
                expr_to_ts(expr, 0)
            } else {
                default_value_for_ts(&ty).to_string()
            };
            out.push_str(&format!("export let {} = $state<{}>({});\n", field.name, ty, default));
        }
        out.push('\n');
    }

    // Methods → exported functions
    for f in &comp.fns {
        if f.name == "template" || f.name == "style" || f.name == "script" {
            continue;
        }
        let params = f
            .params
            .iter()
            .map(|p| format!("{}: {}", p.name, type_to_ts(&p.type_expr)))
            .collect::<Vec<_>>()
            .join(", ");
        let is_async = f
            .return_type
            .as_ref()
            .map(|t| matches!(t, TypeExpr::Result(_)))
            .unwrap_or(false);
        let async_kw = if is_async { "async " } else { "" };
        let ret = match &f.return_type {
            Some(TypeExpr::Result(Some(inner))) => format!(": Promise<{}>", type_to_ts(inner)),
            Some(TypeExpr::Result(None)) => ": Promise<void>".into(),
            Some(ty) => format!(": {}", type_to_ts(ty)),
            None => String::new(),
        };
        out.push_str(&format!("export {}function {}({}){} {{\n", async_kw, f.name, params, ret));
        for expr in &f.body {
            out.push_str(&format!("  {};\n", expr_to_ts(expr, 1)));
        }
        out.push_str("}\n\n");
    }

    SvelteFile { path: path.to_string(), content: out }
}

// ─── SvelteKit Path Resolution ───────────────────────────────────────────────

/// Determine the SvelteKit output path for a UI construct based on its subkind
/// and route annotation.
///
/// - Page → `src/routes/{route}/+page.svelte`
/// - Layout → `src/routes/{route}/+layout.svelte`
/// - Component → `src/lib/components/{Name}.svelte`
/// - Store → `src/lib/stores/{name}.svelte.ts`
pub fn sveltekit_output_path(comp: &Construct, registry: &LayerRegistry) -> String {
    let subkind = comp.subkind.to_lowercase();
    match subkind.as_str() {
        "page" => {
            let route = registry
                .ui_route_path(comp)
                .unwrap_or_else(|| format!("/{}", comp.name.to_lowercase()));
            let segment = route.trim().trim_matches('/');
            if segment.is_empty() {
                "src/routes/+page.svelte".to_string()
            } else {
                format!("src/routes/{}/+page.svelte", segment)
            }
        }
        "layout" => {
            let route = registry
                .ui_route_path(comp)
                .unwrap_or_default();
            let segment = route.trim().trim_matches('/');
            if segment.is_empty() {
                "src/routes/+layout.svelte".to_string()
            } else {
                format!("src/routes/{}/+layout.svelte", segment)
            }
        }
        "store" => {
            format!("src/lib/stores/{}.svelte.ts", to_snake(&comp.name))
        }
        _ => {
            // Default: component
            format!("src/lib/components/{}.svelte", comp.name)
        }
    }
}

/// Convert PascalCase to snake_case for store filenames.
fn to_snake(s: &str) -> String {
    let mut result = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_uppercase() {
            if i > 0 {
                result.push('_');
            }
            result.push(c.to_lowercase().next().unwrap());
        } else {
            result.push(c);
        }
    }
    result
}

// ─── Script Section ──────────────────────────────────────────────────────────

/// Generate the `<script lang="ts">` section content.
///
/// Translates props, state, derived, effects, and methods from the VEIL construct
/// into TsExpr nodes, then emits them as TypeScript text with proper indentation.
fn generate_script_section(comp: &Construct, registry: &LayerRegistry) -> String {
    let mut lines: Vec<String> = Vec::new();
    let pol = &registry.reactivity_policy;

    // Header comment
    lines.push("  // Generated by VEIL".to_string());

    // Detect component references in template for imports
    let template_content = get_raw_block(comp, "template");
    let imports = detect_component_imports(&template_content, &comp.name);
    if !imports.is_empty() {
        lines.push(String::new());
        for imp in &imports {
            lines.push(format!("  import {} from './{}.svelte';", imp, imp));
        }
    }

    // Props block → interface + destructure via $props()
    let props_block = comp.blocks.iter().find(|b| b.keyword == "props");
    if let Some(props) = props_block {
        lines.push(String::new());
        lines.push("  interface Props {".to_string());
        for field in &props.fields {
            let ty = field_type_ts(field);
            let optional = field.default_expr.is_some()
                || ty.contains("null")
                || ty.starts_with("Snippet");
            if optional {
                lines.push(format!("    {}?: {};", field.name, ty));
            } else {
                lines.push(format!("    {}: {};", field.name, ty));
            }
        }
        lines.push("  }".to_string());

        let bindings = build_props_bindings(&props.fields, pol);
        let props_call = if pol.props_call.is_empty() {
            "undefined as any /* no reactivity_policy.props_call */".to_string()
        } else {
            pol.props_call.clone()
        };
        lines.push(format!("  let {{ {} }}: Props = {};", bindings, props_call));
    }

    // State block → $state() runes
    let state_block = comp.blocks.iter().find(|b| b.keyword == "state");
    if let Some(state) = state_block {
        lines.push(String::new());
        for field in &state.fields {
            let ty = field_type_ts(field);
            let default = if let Some(expr) = &field.default_expr {
                expr_to_ts(expr, 1)
            } else {
                default_value_for_ts(&ty).to_string()
            };
            if pol.state_line.is_empty() {
                lines.push(format!("  let {}: {} = {};", field.name, ty, default));
            } else {
                let line = ReactivityPolicy::fill(
                    &pol.state_line,
                    &[
                        ("name", field.name.as_str()),
                        ("type", ty.as_str()),
                        ("default", default.as_str()),
                    ],
                );
                let line = line.trim_end().to_string();
                let line = if line.ends_with(';') { line } else { format!("{};", line) };
                lines.push(format!("  {}", line));
            }
        }
    }

    // Derived block → $derived() runes
    let derived_block = comp.blocks.iter().find(|b| b.keyword == "derived");
    if let Some(derived) = derived_block {
        lines.push(String::new());
        for field in &derived.fields {
            let ty = field_type_ts(field);
            if let Some(expr) = &field.default_expr {
                let expr_str = expr_to_ts(expr, 1);
                if pol.derived_line.is_empty() {
                    lines.push(format!("  let {}: {} = {};", field.name, ty, expr_str));
                } else {
                    let line = ReactivityPolicy::fill(
                        &pol.derived_line,
                        &[("name", field.name.as_str()), ("expr", expr_str.as_str())],
                    );
                    let line = line.trim_end().to_string();
                    let line = if line.ends_with(';') { line } else { format!("{};", line) };
                    lines.push(format!("  {}", line));
                }
            } else if pol.derived_line.is_empty() {
                lines.push(format!("  let {}: {} = undefined as any;", field.name, ty));
            } else {
                let line = ReactivityPolicy::fill(
                    &pol.derived_line,
                    &[("name", field.name.as_str()), ("expr", "undefined as any")],
                );
                let line = line.trim_end().to_string();
                let line = if line.ends_with(';') { line } else { format!("{};", line) };
                lines.push(format!("  {}", line));
            }
        }
    }

    // Effects → $effect() runes
    if !comp.effects.is_empty() {
        lines.push(String::new());
        for eff in &comp.effects {
            let async_body = effect_body_needs_await(&eff.body);
            let mut body = String::new();
            if async_body {
                for expr in &eff.body {
                    body.push_str(&format!("      {};\n", expr_to_ts_async(expr, 3)));
                }
            } else {
                for expr in &eff.body {
                    body.push_str(&format!("    {};\n", expr_to_ts(expr, 2)));
                }
            }
            if !eff.cleanup.is_empty() {
                body.push_str("    return () => {\n");
                for expr in &eff.cleanup {
                    body.push_str(&format!("      {};\n", expr_to_ts(expr, 3)));
                }
                body.push_str("    };\n");
            }
            let body = body.trim_end_matches('\n').to_string();

            let template = if async_body { &pol.effect_async } else { &pol.effect_sync };
            if template.is_empty() {
                lines.push(format!(
                    "  // effect {} (no reactivity_policy.effect_*):",
                    eff.name
                ));
                for line in body.lines() {
                    lines.push(format!("  {}", line));
                }
            } else {
                let filled = ReactivityPolicy::fill(
                    template,
                    &[("name", eff.name.as_str()), ("body", body.as_str())],
                );
                for line in filled.lines() {
                    lines.push(format!("  {}", line));
                }
            }
        }
    }

    // Methods → function declarations
    let method_fns: Vec<_> = comp
        .fns
        .iter()
        .filter(|f| f.name != "template" && f.name != "style" && f.name != "script")
        .collect();
    if !method_fns.is_empty() {
        lines.push(String::new());
        for f in &method_fns {
            let params = f
                .params
                .iter()
                .map(|p| format!("{}: {}", p.name, type_to_ts(&p.type_expr)))
                .collect::<Vec<_>>()
                .join(", ");
            let is_async = f
                .return_type
                .as_ref()
                .map(|t| matches!(t, TypeExpr::Result(_)))
                .unwrap_or(false)
                || effect_body_needs_await(&f.body);
            let async_kw = if is_async { "async " } else { "" };
            lines.push(format!("  {}function {}({}) {{", async_kw, f.name, params));
            for expr in &f.body {
                let line = if is_async {
                    expr_to_ts_async(expr, 2)
                } else {
                    expr_to_ts(expr, 2)
                };
                lines.push(format!("    {};", line));
            }
            lines.push("  }".to_string());
        }
    }

    // Raw script escape hatch
    let client_script = get_raw_block(comp, "script");
    if !client_script.is_empty() {
        lines.push(String::new());
        lines.push("  // raw script block (escape hatch — prefer VEIL fn/effect)".to_string());
        for line in client_script.lines() {
            let t = line.trim();
            if t.is_empty() {
                lines.push(String::new());
            } else {
                lines.push(format!("  {}", t));
            }
        }
    }

    let mut out = lines.join("\n");
    out.push('\n');
    out
}

// ─── Template Section ────────────────────────────────────────────────────────

/// Generate the template section by parsing Svelte template syntax into HtmlExpr nodes.
///
/// Handles common patterns:
/// - HTML elements with attributes
/// - `{expression}` interpolations
/// - `{#if cond}...{:else}...{/if}` conditionals
/// - `{#each items as item}...{/each}` loops
/// - `{@render snippet(args)}` render calls
/// - `{@html expr}` raw HTML injection
///
/// Complex or unrecognized patterns pass through as `HtmlExpr::RawHtml`.
fn generate_template_section(comp: &Construct) -> String {
    let template_content = get_raw_block(comp, "template");

    if template_content.is_empty() {
        // Fallback: check fns named "template" (old pattern)
        let content = get_fn_string_body(comp, "template");
        if content.is_empty() {
            return format!(
                "<!-- veil: empty template shell for {} — add `template` raw block when needed -->\n<div class=\"veil-shell\"></div>",
                comp.name
            );
        }
        return dedent_block(&content);
    }

    dedent_block(&template_content)
}

/// Parse Svelte template text into HtmlExpr nodes.
///
/// This is a best-effort mini-parser. It handles the 80% case for
/// well-structured Svelte templates. Complex nesting or unusual patterns
/// fall through as raw text.
pub fn parse_template_to_html_exprs(input: &str) -> Vec<HtmlExpr> {
    let input = input.trim();
    if input.is_empty() {
        return vec![];
    }

    let mut nodes = Vec::new();
    let chars: Vec<char> = input.chars().collect();
    let mut pos = 0;

    while pos < chars.len() {
        // Skip whitespace between top-level nodes
        if chars[pos].is_whitespace() {
            pos += 1;
            continue;
        }

        if pos < chars.len() && chars[pos] == '{' {
            // Svelte block or interpolation
            if let Some((node, end)) = try_parse_svelte_block(&chars, pos) {
                nodes.push(node);
                pos = end;
                continue;
            }
        }

        if pos < chars.len() && chars[pos] == '<' {
            // HTML comment
            if starts_with_at(&chars, pos, "<!--") {
                if let Some(end) = find_str(&chars, pos, "-->") {
                    let text: String = chars[pos + 4..end].iter().collect();
                    nodes.push(HtmlExpr::Comment(text.trim().to_string()));
                    pos = end + 3;
                    continue;
                }
            }
            // HTML element
            if let Some((node, end)) = try_parse_element(&chars, pos) {
                nodes.push(node);
                pos = end;
                continue;
            }
        }

        // Text content — collect until next `<` or `{`
        let start = pos;
        while pos < chars.len() && chars[pos] != '<' && chars[pos] != '{' {
            pos += 1;
        }
        let text: String = chars[start..pos].iter().collect();
        let text = text.trim();
        if !text.is_empty() {
            nodes.push(HtmlExpr::Text(text.to_string()));
        }
    }

    nodes
}

/// Try to parse a Svelte block (`{#if}`, `{#each}`, `{@render}`, `{@html}`, or interpolation).
fn try_parse_svelte_block(chars: &[char], pos: usize) -> Option<(HtmlExpr, usize)> {
    if pos >= chars.len() || chars[pos] != '{' {
        return None;
    }

    let after_brace = pos + 1;
    if after_brace >= chars.len() {
        return None;
    }

    // {#if condition}...{:else}...{/if}
    if starts_with_at(chars, after_brace, "#if ") {
        return parse_if_block(chars, pos);
    }

    // {#each iterable as binding}...{/each}
    if starts_with_at(chars, after_brace, "#each ") {
        return parse_each_block(chars, pos);
    }

    // {#snippet name(params)}...{/snippet}
    if starts_with_at(chars, after_brace, "#snippet ") {
        return parse_snippet_block(chars, pos);
    }

    // {@render name(args)}
    if starts_with_at(chars, after_brace, "@render ") {
        return parse_render_call(chars, pos);
    }

    // {@html expr}
    if starts_with_at(chars, after_brace, "@html ") {
        return parse_raw_html(chars, pos);
    }

    // Plain interpolation: {expression}
    if let Some(end) = find_matching_brace(chars, pos) {
        let expr: String = chars[pos + 1..end].iter().collect();
        return Some((HtmlExpr::Interpolation(expr.trim().to_string()), end + 1));
    }

    None
}

fn parse_if_block(chars: &[char], pos: usize) -> Option<(HtmlExpr, usize)> {
    // Find the closing }
    let cond_start = pos + 4; // after "{#if "
    let block_open_end = find_char(chars, pos, '}')?;
    let condition: String = chars[cond_start..block_open_end].iter().collect();

    // Find matching {/if}
    let body_start = block_open_end + 1;
    let (then_content, else_content, end_pos) = split_if_else(chars, body_start)?;

    let then_children = parse_inline_content(&then_content);
    let else_children = if else_content.is_empty() {
        None
    } else {
        Some(parse_inline_content(&else_content))
    };

    Some((
        HtmlExpr::Conditional {
            condition: condition.trim().to_string(),
            then_children,
            else_children,
        },
        end_pos,
    ))
}

fn parse_each_block(chars: &[char], pos: usize) -> Option<(HtmlExpr, usize)> {
    // {#each iterable as binding (key)}
    let block_open_end = find_char(chars, pos, '}')?;
    let header: String = chars[pos + 1..block_open_end].iter().collect();
    // Parse: "#each items as item (item.id)"
    let header = header.trim_start_matches("#each ").trim();

    let (iterable, rest) = header.split_once(" as ")?;
    let (binding, key) = if let Some((b, k)) = rest.split_once('(') {
        (b.trim(), Some(k.trim_end_matches(')').trim().to_string()))
    } else {
        (rest.trim(), None)
    };

    // Find body until {/each}
    let body_start = block_open_end + 1;
    let end_tag = "{/each}";
    let end_pos = find_block_end(chars, body_start, end_tag)?;
    let body_content: String = chars[body_start..end_pos].iter().collect();

    let children = parse_inline_content(&body_content);

    Some((
        HtmlExpr::Loop {
            binding: binding.to_string(),
            iterable: iterable.trim().to_string(),
            key,
            children,
        },
        end_pos + end_tag.len(),
    ))
}

fn parse_snippet_block(chars: &[char], pos: usize) -> Option<(HtmlExpr, usize)> {
    let block_open_end = find_char(chars, pos, '}')?;
    let header: String = chars[pos + 1..block_open_end].iter().collect();
    // Parse: "#snippet name(params)"
    let header = header.trim_start_matches("#snippet ").trim();

    let (name, params_str) = if let Some((n, p)) = header.split_once('(') {
        (n.trim(), p.trim_end_matches(')'))
    } else {
        (header, "")
    };

    let params: Vec<String> = if params_str.is_empty() {
        vec![]
    } else {
        params_str.split(',').map(|s| s.trim().to_string()).collect()
    };

    let body_start = block_open_end + 1;
    let end_tag = "{/snippet}";
    let end_pos = find_block_end(chars, body_start, end_tag)?;
    let body_content: String = chars[body_start..end_pos].iter().collect();

    let children = parse_inline_content(&body_content);

    Some((
        HtmlExpr::Snippet {
            name: name.to_string(),
            params,
            children,
        },
        end_pos + end_tag.len(),
    ))
}

fn parse_render_call(chars: &[char], pos: usize) -> Option<(HtmlExpr, usize)> {
    let end = find_char(chars, pos, '}')?;
    let inner: String = chars[pos + 1..end].iter().collect();
    // "@render name(args)"
    let inner = inner.trim_start_matches("@render ").trim();

    let (name, args_str) = if let Some((n, a)) = inner.split_once('(') {
        (n.trim(), a.trim_end_matches(')'))
    } else {
        (inner, "")
    };

    let args: Vec<String> = if args_str.is_empty() {
        vec![]
    } else {
        args_str.split(',').map(|s| s.trim().to_string()).collect()
    };

    Some((
        HtmlExpr::RenderCall {
            name: name.to_string(),
            args,
        },
        end + 1,
    ))
}

fn parse_raw_html(chars: &[char], pos: usize) -> Option<(HtmlExpr, usize)> {
    let end = find_matching_brace(chars, pos)?;
    let inner: String = chars[pos + 1..end].iter().collect();
    let expr = inner.trim_start_matches("@html ").trim().to_string();
    Some((HtmlExpr::RawHtml(expr), end + 1))
}

/// Try to parse an HTML element starting at `<`.
fn try_parse_element(chars: &[char], pos: usize) -> Option<(HtmlExpr, usize)> {
    if pos >= chars.len() || chars[pos] != '<' {
        return None;
    }

    // Skip `<`
    let mut i = pos + 1;

    // Closing tag — not an element start
    if i < chars.len() && chars[i] == '/' {
        return None;
    }

    // Read tag name
    let tag_start = i;
    while i < chars.len() && (chars[i].is_alphanumeric() || chars[i] == '-' || chars[i] == '_' || chars[i] == ':') {
        i += 1;
    }
    if i == tag_start {
        return None;
    }
    let tag: String = chars[tag_start..i].iter().collect();

    // Check if it's a component (PascalCase)
    let is_component = tag.chars().next().map_or(false, |c| c.is_uppercase());

    // Parse attributes
    let mut attrs = Vec::new();
    loop {
        // Skip whitespace
        while i < chars.len() && chars[i].is_whitespace() {
            i += 1;
        }
        if i >= chars.len() {
            return None;
        }

        // Self-closing /> or closing >
        if chars[i] == '/' && i + 1 < chars.len() && chars[i + 1] == '>' {
            i += 2;
            if is_component {
                let props = attrs_to_component_props(&attrs);
                return Some((
                    HtmlExpr::Component { name: tag, props, children: vec![] },
                    i,
                ));
            }
            return Some((
                HtmlExpr::Element { tag, attrs, children: vec![] },
                i,
            ));
        }
        if chars[i] == '>' {
            i += 1;
            break;
        }

        // Parse an attribute
        if let Some((attr, end)) = parse_attr(chars, i) {
            attrs.push(attr);
            i = end;
        } else {
            // Unrecognized — skip char
            i += 1;
        }
    }

    // Check for void elements
    if crate::html::is_void_element(&tag) {
        return Some((HtmlExpr::Element { tag, attrs, children: vec![] }, i));
    }

    // Parse children until closing tag
    let (children, end_pos) = parse_children_until_close(chars, i, &tag);

    if is_component {
        let props = attrs_to_component_props(&attrs);
        Some((HtmlExpr::Component { name: tag, props, children }, end_pos))
    } else {
        Some((HtmlExpr::Element { tag, attrs, children }, end_pos))
    }
}

/// Parse children of an element until we find `</tag>`.
fn parse_children_until_close(chars: &[char], start: usize, tag: &str) -> (Vec<HtmlExpr>, usize) {
    let mut children = Vec::new();
    let mut pos = start;
    let close_tag = format!("</{}>", tag);

    while pos < chars.len() {
        // Check for closing tag
        if starts_with_at(chars, pos, &close_tag) {
            return (children, pos + close_tag.len());
        }

        // Svelte block or interpolation
        if chars[pos] == '{' {
            if let Some((node, end)) = try_parse_svelte_block(chars, pos) {
                children.push(node);
                pos = end;
                continue;
            }
        }

        // Nested element
        if chars[pos] == '<' && pos + 1 < chars.len() && chars[pos + 1] != '/' {
            if let Some((node, end)) = try_parse_element(chars, pos) {
                children.push(node);
                pos = end;
                continue;
            }
        }

        // Text content
        let text_start = pos;
        while pos < chars.len()
            && chars[pos] != '<'
            && chars[pos] != '{'
            && !starts_with_at(chars, pos, &close_tag)
        {
            pos += 1;
        }
        if pos > text_start {
            let text: String = chars[text_start..pos].iter().collect();
            let text = text.trim();
            if !text.is_empty() {
                children.push(HtmlExpr::Text(text.to_string()));
            }
        }
    }

    // If we never found the close tag, return what we have
    (children, pos)
}

/// Parse a single HTML attribute (handles static, dynamic, bind:, on:, spread).
fn parse_attr(chars: &[char], pos: usize) -> Option<(HtmlAttr, usize)> {
    let mut i = pos;

    // Spread: {...expr}
    if i < chars.len() && chars[i] == '{' && i + 3 < chars.len() && chars[i + 1] == '.' && chars[i + 2] == '.' && chars[i + 3] == '.' {
        let end = find_matching_brace(chars, i)?;
        let expr: String = chars[i + 4..end].iter().collect();
        return Some((
            HtmlAttr {
                name: String::new(),
                value: HtmlAttrValue::Spread(expr.trim().to_string()),
            },
            end + 1,
        ));
    }

    // Shorthand: {name} (same as name={name})
    if i < chars.len() && chars[i] == '{' {
        let end = find_matching_brace(chars, i)?;
        let expr: String = chars[i + 1..end].iter().collect();
        let expr = expr.trim().to_string();
        return Some((
            HtmlAttr {
                name: expr.clone(),
                value: HtmlAttrValue::Dynamic(expr),
            },
            end + 1,
        ));
    }

    // Read attribute name
    let name_start = i;
    while i < chars.len()
        && (chars[i].is_alphanumeric() || chars[i] == '-' || chars[i] == '_' || chars[i] == ':' || chars[i] == '.')
    {
        i += 1;
    }
    if i == name_start {
        return None;
    }
    let name: String = chars[name_start..i].iter().collect();

    // Boolean attribute (no value)
    if i >= chars.len() || chars[i] != '=' {
        // Handle bind:value shorthand (no =)
        if name.starts_with("bind:") {
            let prop = name.strip_prefix("bind:").unwrap().to_string();
            return Some((
                HtmlAttr { name: String::new(), value: HtmlAttrValue::Bind(prop) },
                i,
            ));
        }
        return Some((
            HtmlAttr { name, value: HtmlAttrValue::Boolean },
            i,
        ));
    }

    // Skip '='
    i += 1;

    // Handle different value forms
    if i >= chars.len() {
        return Some((HtmlAttr { name, value: HtmlAttrValue::Boolean }, i));
    }

    // Dynamic value: name={expr}
    if chars[i] == '{' {
        let end = find_matching_brace(chars, i)?;
        let expr: String = chars[i + 1..end].iter().collect();

        // Check for on:event or bind:prop
        if name.starts_with("on:") {
            let event = name.strip_prefix("on:").unwrap_or(&name);
            return Some((
                HtmlAttr {
                    name: String::new(),
                    value: HtmlAttrValue::Event(event.to_string(), expr.trim().to_string()),
                },
                end + 1,
            ));
        }
        if name.starts_with("bind:") {
            let prop = name.strip_prefix("bind:").unwrap().to_string();
            return Some((
                HtmlAttr { name: String::new(), value: HtmlAttrValue::Bind(prop) },
                end + 1,
            ));
        }

        return Some((
            HtmlAttr {
                name,
                value: HtmlAttrValue::Dynamic(expr.trim().to_string()),
            },
            end + 1,
        ));
    }

    // Static value: name="value" or name='value'
    if chars[i] == '"' || chars[i] == '\'' {
        let quote = chars[i];
        i += 1;
        let val_start = i;
        while i < chars.len() && chars[i] != quote {
            i += 1;
        }
        let val: String = chars[val_start..i].iter().collect();
        if i < chars.len() {
            i += 1; // skip closing quote
        }

        // Handle on:event with static values
        if name.starts_with("on:") {
            let event = name.strip_prefix("on:").unwrap_or(&name);
            return Some((
                HtmlAttr {
                    name: String::new(),
                    value: HtmlAttrValue::Event(event.to_string(), val),
                },
                i,
            ));
        }

        return Some((
            HtmlAttr { name, value: HtmlAttrValue::Static(val) },
            i,
        ));
    }

    // Bare value (unusual but possible)
    let val_start = i;
    while i < chars.len() && !chars[i].is_whitespace() && chars[i] != '>' && chars[i] != '/' {
        i += 1;
    }
    let val: String = chars[val_start..i].iter().collect();
    Some((
        HtmlAttr { name, value: HtmlAttrValue::Static(val) },
        i,
    ))
}

